#!/usr/bin/env node
/**
 * Generates CLAIMS.md from lib/claims.ts + lib/packages.ts.
 *
 * The manifest is DERIVED, never hand-written — a hand-maintained table would
 * be wrong within two commits. "Appears on" is computed by grepping the source
 * for the claim id, so it cannot drift from what actually renders.
 *
 * Usage:  node scripts/build-claims-manifest.mjs          (writes CLAIMS.md)
 *         node scripts/build-claims-manifest.mjs --check  (prints, writes nothing)
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  ROOT,
  readClaims,
  readPlaceholderPackages,
  readSitePhone,
  sourceFiles,
  readSource,
} from "./lib/read-data.mjs";

/** A phone number where every digit repeats is a dummy, not a real contact. */
function looksLikeDummyPhone(phone) {
  const digits = phone.replace(/\D/g, "");
  return /^(\d)\1+$/.test(digits);
}

export function buildManifest() {
  const claims = readClaims();
  const placeholders = readPlaceholderPackages();
  const phone = readSitePhone();
  const phoneIsPlaceholder = looksLikeDummyPhone(phone);
  const files = sourceFiles();

  // Where each claim id actually appears. Only <Claim id="..."/> counts as a
  // render, which is the whole point of routing every metric through that
  // component — usage becomes greppable rather than guessed at.
  const usage = new Map(claims.map((c) => [c.id, []]));
  for (const file of files) {
    const lines = readSource(file).split("\n");
    lines.forEach((line, i) => {
      for (const claim of claims) {
        if (line.includes(`id="${claim.id}"`)) {
          usage.get(claim.id).push(`${file}:${i + 1}`);
        }
      }
    });
  }

  const flagged = claims.filter((c) => c.reviewNote);
  const unused = claims.filter((c) => usage.get(c.id).length === 0 && !c.reserved);
  const reserved = claims.filter((c) => usage.get(c.id).length === 0 && c.reserved);

  const L = [];
  L.push("# Published claims — review manifest");
  L.push("");
  L.push("> GENERATED by `scripts/build-claims-manifest.mjs`. Do not edit by hand.");
  L.push("> Regenerate: `npm run claims:build` · Verify: `npm run claims:check`");
  L.push("");
  L.push(
    "Every factual claim on the public site is listed here with its source in the private `whoami` repo and every page it appears on. Source references are file + section only — never a verbatim quote, since this repo is public and `whoami` is not.",
  );
  L.push("");

  // ---- the part that needs a human decision, first ----
  L.push("## Needs your decision");
  L.push("");
  if (flagged.length === 0) {
    L.push("_None._");
  } else {
    L.push(
      `${flagged.length} claim(s) are registered but carry a risk I want you to rule on explicitly. No script can make these calls.`,
    );
    L.push("");
    for (const c of flagged) {
      const where = usage.get(c.id);
      L.push(`### \`${c.id}\``);
      L.push("");
      L.push(`**Renders as:** ${c.text}`);
      L.push("");
      L.push(
        `**Currently on:** ${where.length ? where.join(" · ") : "**no page** (registered only)"}`,
      );
      L.push("");
      L.push(`**Source:** whoami / ${c.file} / ${c.section}${c.row ? ` / ${c.row}` : ""}`);
      L.push("");
      L.push(`**Why flagged:** ${c.reviewNote}`);
      L.push("");
    }
  }

  // ---- placeholders that must not reach production ----
  L.push("## Placeholders — must be replaced before production");
  L.push("");
  const placeholderRows = [
    ...placeholders.map(
      (p) => `| ${p.name} (\`${p.id}\`) | lib/packages.ts · /for-individuals | Draft price |`,
    ),
    ...(phoneIsPlaceholder
      ? [`| Phone number | lib/site.ts · /contact | \`${phone}\` is a placeholder |`]
      : []),
  ];
  if (placeholderRows.length === 0) {
    L.push("_None. Safe to launch on this axis._");
  } else {
    L.push("| Item | Where | Status |");
    L.push("| --- | --- | --- |");
    L.push(...placeholderRows);
  }
  L.push("");

  // ---- the full registry ----
  L.push("## All claims");
  L.push("");
  for (const c of claims) {
    const where = usage.get(c.id);
    L.push(`### \`${c.id}\`  ·  ${c.kind}  ·  verified ${c.verifiedOn}`);
    L.push("");
    L.push(`- **Published text:** ${c.text}`);
    L.push(`- **Source:** whoami / ${c.file} / ${c.section}${c.row ? ` / ${c.row}` : ""}`);
    L.push(
      `- **Appears on:** ${where.length ? where.join(" · ") : c.reserved ? "_reserved — not on any page_" : "**UNUSED**"}`,
    );
    if (c.reviewNote) L.push(`- **Flagged:** see "Needs your decision" above`);
    L.push("");
  }

  L.push("## Summary");
  L.push("");
  L.push(`- Registered: ${claims.length}`);
  L.push(`- Live on a page: ${claims.filter((c) => usage.get(c.id).length > 0).length}`);
  L.push(`- Reserved (deliberately not placed): ${reserved.length}`);
  L.push(`- Unused (should be placed or marked reserved): ${unused.length}`);
  L.push(`- Flagged for your decision: ${flagged.length}`);
  L.push(`- Placeholders blocking launch: ${placeholderRows.length}`);
  L.push("");

  return L.join("\n");
}

// Only act when invoked directly — check-claims.mjs imports buildManifest()
// and must not trigger a write as a side effect.
const invokedDirectly =
  process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;

if (invokedDirectly) {
  const manifest = buildManifest();
  if (process.argv.includes("--check")) {
    process.stdout.write(manifest);
  } else {
    writeFileSync(join(ROOT, "CLAIMS.md"), manifest);
    console.log("CLAIMS.md written");
  }
}
